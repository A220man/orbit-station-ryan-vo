import json
from typing import Dict, Any, Optional
import httpx
from app.core.config import settings

def generate_fallback_analysis_advisory(
    workload_summary: Dict[str, Any],
    custom_prompt: Optional[str] = None
) -> Dict[str, Any]:
    """
    Opt-in LLM advisory analysis. Labeled advisory only.
    Strictly offline deterministic fallback when no LLM_API_KEY is supplied.
    """
    if not settings.llm_api_key:
        # Fully deterministic grounded offline advisory
        backend = workload_summary.get("target_backend", "mps")
        coverage = workload_summary.get("coverage_score", 0.0)
        fallbacks = workload_summary.get("fallbacks", [])
        
        advice_points = [
            f"Target backend '{backend}' achieves an estimated {coverage}% native operator execution.",
            f"A total of {len(fallbacks)} operator(s) require host memory round-trips to CPU kernels, which may introduce PCIe/unified memory synchronization barriers."
        ]
        if coverage < 70.0:
            advice_points.append(
                "Recommendation: Group CPU fallback operations at the beginning or end of the computational graph to minimize synchronization overhead."
            )
        else:
            advice_points.append(
                "Recommendation: Direct execution graph is well-suited for high-throughput stream execution on the target hardware."
            )

        return {
            "status": "deterministic_offline",
            "advisory_label": "Deterministic Offline Analysis (No LLM key configured)",
            "provider": "offline-engine",
            "model": "built-in-rules",
            "findings": advice_points,
            "disclaimer": "This analysis is deterministic advice derived from operator coverage metrics. No external inference call was made."
        }

    # If key is provided, format prompt and invoke configured provider
    prompt_text = (
        f"Analyze this PyTorch workload execution profile for target {workload_summary.get('target_backend')}:\n"
        f"Coverage Score: {workload_summary.get('coverage_score')}%\n"
        f"Fallbacks: {json.dumps(workload_summary.get('fallbacks', []))}\n"
        "Provide 3 concise actionable engineering recommendations."
    )

    try:
        if settings.llm_provider == "anthropic":
            url = settings.llm_base_url or "https://api.anthropic.com/v1/messages"
            headers = {
                "x-api-key": settings.llm_api_key,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json"
            }
            body = {
                "model": settings.llm_model,
                "max_tokens": 400,
                "messages": [{"role": "user", "content": prompt_text}]
            }
            with httpx.Client(timeout=10.0) as client:
                res = client.post(url, headers=headers, json=body)
                res.raise_for_status()
                data = res.json()
                text = data["content"][0]["text"]
        elif settings.llm_provider == "gemini":
            base = settings.llm_base_url or "https://generativelanguage.googleapis.com/v1beta"
            url = f"{base}/models/{settings.llm_model}:generateContent?key={settings.llm_api_key}"
            headers = {"content-type": "application/json"}
            body = {
                "contents": [{"parts": [{"text": prompt_text}]}]
            }
            with httpx.Client(timeout=10.0) as client:
                res = client.post(url, headers=headers, json=body)
                res.raise_for_status()
                data = res.json()
                text = data["candidates"][0]["content"]["parts"][0]["text"]
        else: # openai-compatible / ollama
            url = (settings.llm_base_url or "https://api.openai.com/v1").rstrip("/") + "/chat/completions"
            headers = {
                "Authorization": f"Bearer {settings.llm_api_key}",
                "Content-Type": "application/json"
            }
            body = {
                "model": settings.llm_model,
                "messages": [{"role": "user", "content": prompt_text}],
                "max_tokens": 400
            }
            with httpx.Client(timeout=10.0) as client:
                res = client.post(url, headers=headers, json=body)
                res.raise_for_status()
                data = res.json()
                text = data["choices"][0]["message"]["content"]

        return {
            "status": "success",
            "advisory_label": "Advisory Only (AI Model Insights)",
            "provider": settings.llm_provider,
            "model": settings.llm_model,
            "findings": [t.strip() for t in text.split("\n") if t.strip()],
            "disclaimer": "Advisory text generated by configured provider. Always verify operator behavior with empirical tests."
        }
    except Exception as e:
        return {
            "status": "provider_error",
            "advisory_label": "Advisory Request Failed",
            "provider": settings.llm_provider,
            "error_detail": f"Provider connection error: {type(e).__name__}",
            "findings": [
                "Unable to contact external advisory service.",
                "Defaulting to local deterministic evaluation metrics."
            ],
            "disclaimer": "External service failed; empirical benchmarks remain valid."
        }
